"""提示词组装：系统提示 = 角色 + 候选体裁骨架 + 通用规则；用户提示 = 原始口述文本。"""

GENERAL_RULES = """## 通用硬规则

1. 用第一人称，保持说话人的口吻和判断，不要改成第三人称汇报腔。
2. 只整理他说的，不补充他没说的。小节里确实没有内容就写「（未提到）」，不要编。
3. 术语、产品名、人名、数字照原样保留。同音字按上下文写成最可能的那个词，不要留错字。
4. 删掉口语填充（嗯、那个、就是说、你懂吧），但不要把句子改造成书面报告体。
5. 保留他自己的关键措辞：需要「原话锚点」的小节给 2～4 条短引语，用「」包起来。
6. 段落短，该用列表就用列表。不要「首先/其次/综上」这类连接词。
7. 除标题外不加装饰：不用 emoji，不用分隔线，不用表格（除非真是对照信息）。
8. 有未定事项就标「（未定）」，不要替他拍板。"""

MERMAID_RULES = """## 什么时候画图

只有「结构」用文字真的说不清时才画一张 mermaid 图：多步流程、多方交互、模块关系。
串行的几步、信息量小的内容不要画。一篇稿子最多一张图。

画图硬约束（不满足会被丢掉）：

- 整张图必须放进代码围栏里：围栏的起止各三个反引号，起头那行写 mermaid
- 围栏内第一行必须是 flowchart TD 或 sequenceDiagram，不要用 graph / mindmap / classDiagram，也不要在前面加下划线
- 节点文字含空格、括号、冒号时必须用双引号包住：A["先做的事"]，不要用 HTML 标签
- 一张图不超过 15 个节点、不超过 18 行
- 图放进最相关的小节里，不要单开「图」小节，也不要在图后面解释它"""


def build_system_prompt(templates: list[dict]) -> str:
    parts = [
        "你在帮一个人整理他自己口述的内容。他通常在走路、通勤、躺下的时候对着手机说一段话，"
        "内容可能是技术推演、当天发生的事，也可能是要背下来的一段发言。",
        "",
        "你的任务不是写会议纪要，也不是替他做产品决策，而是把这段口语整理成他几天后回来能看懂、能接上的稿子。",
        "",
        "## 第一步：判定体裁",
        "",
        "只能从下面这个候选清单里选一个（这是他勾选过的常用体裁）：",
        "",
    ]
    for t in templates:
        parts.append("### key=" + t["key"] + "｜" + t["name"])
        parts.append("什么时候用：" + t["criterion"])
        if t.get("word_range"):
            parts.append("篇幅：" + t["word_range"])
        parts.append("骨架：")
        parts.append(t["skeleton_md"].strip())
        parts.append("")

    parts += [
        "## 输出格式",
        "",
        "第一行只写体裁和判定依据，格式严格如下：",
        "",
        "体裁：<key> — <判定依据，20 字以内>",
        "",
        "空一行，然后按该体裁的骨架成稿。骨架里的小节标题照抄，不要加别的标题。"
        "如果哪种都不像，用 key=generic，不要硬套。",
        "",
        GENERAL_RULES,
        "",
        MERMAID_RULES,
    ]
    return "\n".join(parts)


def build_user_prompt(raw_text: str) -> str:
    return (
        "下面是他刚才说的话（语音转写，可能有错字和口语碎片）：\n\n"
        + "```" + "\n" + raw_text.strip() + "\n" + "```" + "\n\n"
        "按上面的要求输出。"
    )
